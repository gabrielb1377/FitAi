import '../../models/exercicio_model.dart';
import 'exercise_catalog_identity.dart';
import 'exercise_identity.dart';

/// Origin-specific methods accepted at the catalog binding boundary.
enum ExerciseCatalogBindingMethod {
  canonical,
  legacy,
  exactName,
  alias,
  manual,
  ambiguous,
  unresolved,
}

enum ExerciseCatalogBindingStatus { resolved, ambiguous, unresolved }

/// Result of resolving an upstream exercise reference against `bancoExercicios`.
///
/// The three upstream concepts deliberately remain distinct: [templateItemId]
/// identifies the item in a template/AI payload, [remoteExerciseId] belongs to
/// the API catalog when present, and [canonicalExerciseId] is the local FitIA
/// catalog identity used by media, history and future integrations.
class ExerciseCatalogBinding {
  const ExerciseCatalogBinding({
    required this.templateItemId,
    required this.remoteExerciseId,
    required this.sourceName,
    required this.status,
    required this.method,
    this.entry,
  });

  final String templateItemId;
  final String remoteExerciseId;
  final String sourceName;
  final ExerciseCatalogBindingStatus status;
  final ExerciseCatalogBindingMethod method;
  final ExerciseCatalogEntry? entry;

  bool get isResolved => status == ExerciseCatalogBindingStatus.resolved;
  String get canonicalExerciseId => entry?.canonicalId ?? '';
  String get canonicalName => entry?.canonicalName ?? '';
  String get mediaKey => entry?.mediaKey ?? '';
}

/// Deterministic binding boundary for templates and responses generated by AI.
///
/// It only accepts a canonical ID, a safe legacy redirect, a unique name/alias,
/// or an explicit editorial mapping. It never guesses by fuzzy similarity.
class ExerciseCatalogBinder {
  ExerciseCatalogBinder(
    Iterable<ExercicioModel> exercises, {
    Map<String, String> templateManualMappings = defaultTemplateManualMappings,
  }) : _identity = ExerciseCatalogIdentity(exercises),
       _templateManualMappings = Map.unmodifiable(templateManualMappings) {
    for (final entry in _identity.entries) {
      _entriesByNormalizedName
          .putIfAbsent(
            ExerciseIdentity.normalizeName(entry.canonicalName),
            () => <ExerciseCatalogEntry>[],
          )
          .add(entry);
    }
  }

  /// Editorial mappings for the current ready-plan seed. These are not a
  /// second catalog: each value is an existing immutable catalog ID, reviewed
  /// against the seed's exercise context. Do not add fuzzy aliases here.
  static const defaultTemplateManualMappings = <String, String>{
    'triceps na polia': 'triceps_026',
    'remada baixa': 'costas_006',
    'rosca direta': 'biceps_001',
    'agachamento livre': 'pernas_001',
    'leg press': 'pernas_002',
    'mesa flexora': 'pernas_004',
    'panturrilha em pe': 'pernas_009',
    'agachamento goblet': 'pernas_019',
    'cadeira extensora': 'pernas_003',
    'prancha': 'abdomen_002',
    'levantamento terra': 'pernas_030',
    'agachamento com peso corporal': 'funcional_001',
    'flexao de bracos': 'funcional_002',
    'afundo alternado': 'funcional_003',
    'elevacao de pernas': 'abdomen_004',
    'remada curvada': 'costas_002',
  };

  final ExerciseCatalogIdentity _identity;
  final Map<String, List<ExerciseCatalogEntry>> _entriesByNormalizedName =
      <String, List<ExerciseCatalogEntry>>{};
  final Map<String, String> _templateManualMappings;

  /// Binds a ready-plan item. A remote UUID is preserved as metadata but is
  /// never promoted to the local catalog identity.
  ExerciseCatalogBinding bindTemplate({
    required String templateItemId,
    required String remoteExerciseId,
    required String exerciseName,
    String canonicalExerciseId = '',
  }) => _bind(
    templateItemId: templateItemId,
    remoteExerciseId: remoteExerciseId,
    sourceName: exerciseName,
    suppliedCanonicalExerciseId: canonicalExerciseId,
    allowTemplateManualMapping: true,
  );

  /// Binds an already validated AI response. Unknown values are explicit so a
  /// generated plan cannot be persisted with a fabricated or remote ID.
  ExerciseCatalogBinding bindAi({
    required String templateItemId,
    required String remoteExerciseId,
    required String exerciseName,
    String canonicalExerciseId = '',
  }) => _bind(
    templateItemId: templateItemId,
    remoteExerciseId: remoteExerciseId,
    sourceName: exerciseName,
    suppliedCanonicalExerciseId: canonicalExerciseId,
    allowTemplateManualMapping: false,
  );

  ExerciseCatalogBinding _bind({
    required String templateItemId,
    required String remoteExerciseId,
    required String sourceName,
    required String suppliedCanonicalExerciseId,
    required bool allowTemplateManualMapping,
  }) {
    final canonical = suppliedCanonicalExerciseId.trim();
    if (canonical.isNotEmpty) {
      final resolution = _identity.resolve(exerciseId: canonical);
      if (resolution != null) {
        return _resolved(
          templateItemId: templateItemId,
          remoteExerciseId: remoteExerciseId,
          sourceName: sourceName,
          entry: resolution.entry,
          method: resolution.kind == ExerciseCatalogIdKind.legacy
              ? ExerciseCatalogBindingMethod.legacy
              : ExerciseCatalogBindingMethod.canonical,
        );
      }
      return _unresolved(
        templateItemId: templateItemId,
        remoteExerciseId: remoteExerciseId,
        sourceName: sourceName,
      );
    }

    final normalizedName = ExerciseIdentity.normalizeName(sourceName);
    final exactMatches = _entriesByNormalizedName[normalizedName];
    if (exactMatches?.length == 1) {
      return _resolved(
        templateItemId: templateItemId,
        remoteExerciseId: remoteExerciseId,
        sourceName: sourceName,
        entry: exactMatches!.single,
        method: ExerciseCatalogBindingMethod.exactName,
      );
    }

    final alias = _identity.resolve(nameOrAlias: sourceName);
    if (alias != null) {
      return _resolved(
        templateItemId: templateItemId,
        remoteExerciseId: remoteExerciseId,
        sourceName: sourceName,
        entry: alias.entry,
        method: ExerciseCatalogBindingMethod.alias,
      );
    }

    if (allowTemplateManualMapping) {
      final mappedId = _templateManualMappings[normalizedName];
      final mapped = mappedId == null
          ? null
          : _identity.resolve(exerciseId: mappedId);
      if (mapped != null) {
        return _resolved(
          templateItemId: templateItemId,
          remoteExerciseId: remoteExerciseId,
          sourceName: sourceName,
          entry: mapped.entry,
          method: ExerciseCatalogBindingMethod.manual,
        );
      }
    }

    return ExerciseCatalogBinding(
      templateItemId: templateItemId.trim(),
      remoteExerciseId: remoteExerciseId.trim(),
      sourceName: sourceName.trim(),
      status: exactMatches != null && exactMatches.length > 1
          ? ExerciseCatalogBindingStatus.ambiguous
          : ExerciseCatalogBindingStatus.unresolved,
      method: exactMatches != null && exactMatches.length > 1
          ? ExerciseCatalogBindingMethod.ambiguous
          : ExerciseCatalogBindingMethod.unresolved,
    );
  }

  ExerciseCatalogBinding _resolved({
    required String templateItemId,
    required String remoteExerciseId,
    required String sourceName,
    required ExerciseCatalogEntry entry,
    required ExerciseCatalogBindingMethod method,
  }) => ExerciseCatalogBinding(
    templateItemId: templateItemId.trim(),
    remoteExerciseId: remoteExerciseId.trim(),
    sourceName: sourceName.trim(),
    status: ExerciseCatalogBindingStatus.resolved,
    method: method,
    entry: entry,
  );

  ExerciseCatalogBinding _unresolved({
    required String templateItemId,
    required String remoteExerciseId,
    required String sourceName,
  }) => ExerciseCatalogBinding(
    templateItemId: templateItemId.trim(),
    remoteExerciseId: remoteExerciseId.trim(),
    sourceName: sourceName.trim(),
    status: ExerciseCatalogBindingStatus.unresolved,
    method: ExerciseCatalogBindingMethod.unresolved,
  );
}
